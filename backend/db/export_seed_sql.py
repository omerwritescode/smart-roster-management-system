"""Write supabase/seed.sql from the sample data: python -m backend.db.export_seed_sql

For anyone who prefers pasting SQL into the Supabase editor to running Python.
Needs a database connection only to quote values correctly; nothing is changed.
"""
from __future__ import annotations

import json
from pathlib import Path

import psycopg
from psycopg import ClientCursor

from . import seed_data as s
from .database import database_url
from .seed import _rule_id

OUT = Path(__file__).resolve().parents[2] / "supabase" / "seed.sql"


def main() -> None:
    lines = ["-- Generated by backend/db/export_seed_sql.py. Fictional sample data.", "begin;"]
    with psycopg.connect(database_url(), cursor_factory=ClientCursor) as conn:
        cur = conn.cursor()

        def add(sql: str, rows) -> None:
            for row in rows:
                lines.append(cur.mogrify(sql, row) + ";")

        add("insert into pods (id, name) values (%s, %s)", [(p[0], p[1]) for p in s.PODS])
        add("insert into employees (id, name, pod_id, title, weekly_off_policy, fixed_off_weekdays, rotation_weekdays) values (%s, %s, %s, %s, %s, %s::int[], %s::int[])",
            [(e[0], e[1], e[2], e[3], e[4], list(e[5]), list(e[6])) for e in s.EMPLOYEES])
        add("update pods set lead_employee_id = %s where id = %s", [(p[2], p[0]) for p in s.PODS])
        add("insert into shifts (id, name, start_time, end_time) values (%s, %s, %s, %s)", s.SHIFTS)
        add("insert into processes (id, code, name) values (%s, %s, %s)", s.PROCESSES)
        add("insert into brands (id, name, pod_id) values (%s, %s, %s)", [b[:3] for b in s.BRANDS])
        add("insert into public_holidays (date, name, kind) values (%s, %s, %s)", s.HOLIDAYS)
        add("insert into brand_processes (id, brand_id, process_id, calendar_type, weekday_mask, shift_id) values (%s, %s, %s, %s, %s::int[], %s)",
            [(r[0], r[1], r[2], r[3], list(r[4]), r[5]) for r in s.brand_processes()])
        add("insert into coverage_rules (id, brand_process_id, rule_type, weekday, date, min_staff, note) values (%s, %s, %s, %s, %s, %s, %s)",
            [(_rule_id(r), *r) for r in s.COVERAGE_RULES])
        add("insert into allocations (id, employee_id, brand_process_id, role, workload_share) values (%s, %s, %s, %s, %s)", s.allocations())
        add("insert into leaves (id, employee_id, leave_type, status, start_date, end_date, reason) values (%s, %s, %s, %s, %s, %s, %s)", s.LEAVES)
        add("insert into comp_off_ledger (employee_id, delta, entry_date, reason) values (%s, %s, '2026-11-30', 'Opening balance')", s.COMP_OFF_OPENING)
        add("insert into comp_off_ledger (employee_id, delta, entry_date, reason, leave_id) values (%s, %s, %s, 'Comp-off taken', %s)",
            [(x[1], -((x[5] - x[4]).days + 1), x[4], x[0]) for x in s.LEAVES if x[2] == "comp_off" and x[3] == "approved"])
        add("insert into preferences (employee_id, pref_type, weekday, date, shift_id, weight) values (%s, %s, %s, %s, %s, %s)", s.PREFERENCES)
        add("insert into app_settings (key, value) values (%s, %s)", [(k, json.dumps(v)) for k, v in s.SETTINGS.items()])
    lines.append("commit;")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"Wrote {OUT} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
